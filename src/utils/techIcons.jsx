export function getTechBadge(tag) {
  const raw = (tag || '').trim()
  const normalized = raw.toLowerCase()
  
  // 1. Exact match
  if (techIconMap[normalized]) {
    return { ...techIconMap[normalized], name: raw, isFallback: false }
  }

  // 2. Substring match
  const keys = Object.keys(techIconMap).sort((a, b) => b.length - a.length)
  for (const key of keys) {
    if (normalized === key) {
      return { ...techIconMap[key], name: raw, isFallback: false }
    }
  }
  for (const key of keys) {
    if (normalized.includes(key)) {
      return { ...techIconMap[key], name: raw, isFallback: false }
    }
  }

  return {
    name: raw,
    color: '#A1A1AA',
    isFallback: true,
    svg: null,
  }
}
